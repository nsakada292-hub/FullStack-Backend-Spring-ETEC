public class Loop {
    static void main(String[] args) {
        // do while loop
        int i=10;
        do {
            System.out.println(i);
            i++;
        }while (i<20);

        // while loop
        int j=11;
        while (j<20){
            System.out.println(j);
            j++;
        }

        // for loop
        for (int k=0; k<10; k++){
            System.out.println(k);
        }
    }
}
